#!/usr/bin/env python3
"""Which part of the block does the damping -- the source line, or the key/value syntax?

The paper shows a Source/Claim block moves the model less than the same sentence sent plainly.
That leaves the mechanism open: the block adds an attributed source AND a key/value frame at the
same time, so "packaging damps" could be either. The reviews asked for the two to be separated.

No new runs are needed. Three conditions already sit on the same claim:

    bare_true       the proposition as a plain sentence
    detclaim_true   Source: ... / Claim: "..."          -- source and frame, no third field
    true_high       Source: ... / Claim: "..." / Confidence: high

so the step from bare to detclaim isolates source-plus-frame, and detclaim to true_high isolates
adding the declared field on top. Nemotron's unswapped true-high pass was written under a `_T`
suffix by the confidence-scale battery; the block text is identical, which is what makes it the
same condition, and the loader below accepts either name.
"""
from __future__ import annotations
import sys
sys.path.insert(0, "scripts")
import numpy as np
import analyse_cascade_v2 as C

CELLS = [("Qwen2.5", "s2"), ("Qwen3", "s2q3"), ("Qwen2-Audio", "nm_qwen2audio"),
         ("AF3", "nm_af3"), ("Nemotron", "nm_nemotron")]


def load(pfx, cond, sfx):
    return (C.L(f"{pfx}_sound_{cond}{sfx}") or C.L(f"{pfx}_sound_{cond}_T{sfx}")
            or C.L(f"{pfx}_sound_{cond}{sfx}_T"))


def step(pfx, a, b):
    """Order-averaged a-minus-b accuracy, source-video bootstrap, on the shared clips."""
    pts, per = [], []
    for sfx in ("", "_swap"):
        A, B = load(pfx, a, sfx), load(pfx, b, sfx)
        if A is None or B is None:
            continue
        ks = sorted(set(A) & set(B))
        d = np.array([A[k]["correct"] - B[k]["correct"] for k in ks], dtype=float)
        pts.append(d.mean() * 100)
        per.append((d, ks))
    if not per:
        return None
    vids = sorted({C.video(k) for _, ks in per for k in ks})
    vi = {v: i for i, v in enumerate(vids)}
    bk = [[np.where(np.array([vi[C.video(k)] for k in ks]) == i)[0] for i in range(len(vids))]
          for _, ks in per]
    rng = np.random.default_rng(0)
    bs = []
    for _ in range(2000):
        sel = rng.integers(0, len(vids), len(vids))
        vals = []
        for (d, _), b_ in zip(per, bk):
            idx = np.concatenate([b_[i] for i in sel if b_[i].size])
            if idx.size:
                vals.append(d[idx].mean() * 100)
        if vals:
            bs.append(float(np.mean(vals)))
    return float(np.mean(pts)), float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


if __name__ == "__main__":
    print("true claim: 평문 → Source/Claim 블록 → 블록+Confidence (정확도 점, 95% CI)")
    print(f"{'셀':12} {'블록화(src+frame)':>22} {'필드 추가':>22}")
    print("-" * 60)
    frame, field = [], []
    for nm, pfx in CELLS:
        s1 = step(pfx, "detclaim_true", "bare_true")     # plain -> source+frame
        s2 = step(pfx, "true_high", "detclaim_true")     # + declared field
        f = lambda r: "--" if r is None else f"{r[0]:+6.1f} [{r[1]:+5.1f},{r[2]:+5.1f}]"
        print(f"{nm:12} {f(s1):>22} {f(s2):>22}")
        if s1: frame.append((nm, s1))
        if s2: field.append((nm, s2))
    prim_f = [(n, r) for n, r in frame if n != "AF3"]
    prim_d = [(n, r) for n, r in field if n != "AF3"]
    import pathlib as _p
    fv = sorted(r[0] for _, r in prim_f); dv = sorted(r[0] for _, r in prim_d)
    _p.Path("paper/auto_packcomp.tex").write_text(
        "% Generated by scripts/analyse_packcomp_v1.py -- do not edit by hand.\n"
        + f"\\newcommand{{\\FrameMin}}{{{-fv[-1]:.1f}}}\n"
        + f"\\newcommand{{\\FrameMax}}{{{-fv[0]:.1f}}}\n"
        + f"\\newcommand{{\\FrameNegN}}{{{sum(1 for _, r in prim_f if r[2] < 0)}}}\n"
        + f"\\newcommand{{\\FieldMin}}{{{dv[0]:.1f}}}\n"
        + f"\\newcommand{{\\FieldMax}}{{{dv[-1]:.1f}}}\n"
        + f"\\newcommand{{\\FieldPosN}}{{{sum(1 for _, r in prim_d if r[1] > 0)}}}\n"
        + f"\\newcommand{{\\PackCompN}}{{{len(prim_f)}}}\n")
    print("paper/auto_packcomp.tex 작성")
    for lbl, xs in (("블록화", frame), ("필드 추가", field)):
        if not xs:
            continue
        neg = [n for n, r in xs if r[2] < 0]
        v = sorted(r[0] for _, r in xs)
        print(f"\n{lbl}: {v[0]:+.1f}..{v[-1]:+.1f}점, CI가 0 아래 {len(neg)}/{len(xs)} {neg}")
