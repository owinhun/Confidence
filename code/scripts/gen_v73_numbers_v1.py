#!/usr/bin/env python3
"""v73 macros: directional audit of the bare-forwarding loss, the claim-step dominance count,
and the strong probe's Nemotron interval. Reads outputs/ and the existing generator macros only.

Direction split (post-hoc, 2026-09-06): clips are split by (truth, detector decision). FN = false
absence claim, FP = false presence claim. Conditional effect = plain - omit on that subset, order-
averaged, accuracy points. Source-video clusters use the 11-char YouTube id (analyse_cascade_v2's
split('_')[0] misparses ids containing '_'; effect on Table 4 CIs <= 0.4 pp, recorded in log_v1.md).
"""
import json, os, re, subprocess
import numpy as np
OUT = "outputs"; BOOTS = 2000
PRIM = [("Qwen2.5-Omni","s2"),("Qwen3-Omni","s2q3"),("Qwen2-Audio","nm_qwen2audio"),("Nemotron/sound","nm_nemotron")]
def L(name):
    p=f"{OUT}/{name}_v1.jsonl"
    if not os.path.exists(p): return None
    d={json.loads(l)["clip"]:json.loads(l) for l in open(p) if l.strip()}
    return d if len(d)>=400 else None
def vid(c):
    b=os.path.basename(c); m=re.match(r"^(.{11})_\d{6}",b); return m.group(1) if m else b
def effect(orders, ks):
    vids=sorted({vid(k) for k in ks}); vi={v:i for i,v in enumerate(vids)}
    gi=np.array([vi[vid(k)] for k in ks]); buckets=[np.where(gi==i)[0] for i in range(len(vids))]
    ds=[np.array([a[k]["correct"]-b[k]["correct"] for k in ks],float) for a,b in orders]
    pt=float(np.mean([d.mean()*100 for d in ds]))
    rng=np.random.default_rng(0); bs=[]
    for _ in range(BOOTS):
        sel=rng.integers(0,len(vids),len(vids)); idx=np.concatenate([buckets[i] for i in sel if buckets[i].size])
        bs.append(float(np.mean([d[idx].mean()*100 for d in ds])))
    return pt,float(np.percentile(bs,2.5)),float(np.percentile(bs,97.5))
M={}
def put(k,v,nd=1): M[k]=v if isinstance(v,str) else f"{v:.{nd}f}"
D=L("clap_cascade"); fn=[];fp=[];exceed=0;share=[]
for name,pfx in PRIM:
    orders=[(L(f"{pfx}_sound_cascadex_plain{t}"),L(f"{pfx}_sound_none{t}")) for t in ("","_swap")]
    orders=[o for o in orders if all(o)]
    keys=sorted(set.intersection(*(set(a)&set(b) for a,b in orders))&set(D))
    cat={k:(("TP" if D[k]["det_pred"]=="A" else "FN") if D[k]["label"]=="A" else ("FP" if D[k]["det_pred"]=="A" else "TN")) for k in keys}
    kf=[k for k in keys if cat[k]=="FN"]; kp=[k for k in keys if cat[k]=="FP"]
    ef=effect(orders,kf); ep=effect(orders,kp); tot=effect(orders,keys)
    fn.append(-ef[0]); fp.append(-ep[0])
    share.append(100*ef[0]*len(kf)/(ef[0]*len(kf)+ep[0]*len(kp)))   # FN share of the gross false-claim loss
    if ef[0]*len(kf)/len(keys) < tot[0]: exceed+=1
    assert ef[2]<0 and ep[2]<0, (name, ef, ep)
put("DirFNCondMin",min(fn)); put("DirFNCondMax",max(fn)); put("DirFPCondMin",min(fp)); put("DirFPCondMax",max(fp))
put("DirExceedN",str(exceed)); put("DirCells",str(len(PRIM)))
put("DirFNShareMin",min(share),0); put("DirFNShareMax",max(share),0)
put("DetFNn",str(sum(1 for k in D if D[k]["label"]=="A" and D[k]["det_pred"]=="B")))
put("DetFPn",str(sum(1 for k in D if D[k]["label"]=="B" and D[k]["det_pred"]=="A")))
t=open("paper/auto_numbers.tex").read()
blk=re.search(r"\\newcommand\{\\TabMerged\}\{%\n(.*?)\n\}",t,re.S).group(1)
largest=twice=n=0
for row in blk.strip().splitlines():
    cells=[c.strip() for c in row.rstrip("\\ ").split("&")]
    steps=[abs(float(cells[i].strip("$"))) for i in (1,2,3,4)]
    n+=1; others=sorted(steps[:2]+steps[3:],reverse=True)[0]
    largest+=steps[2]==max(steps); twice+=steps[2]>2*others
put("StepCells",str(n)); put("ClaimLargestN",str(largest)); put("ClaimTwiceN",str(twice))
so=subprocess.run(["python3","scripts/analyse_strong_v1.py"],capture_output=True,text=True).stdout
m=re.search(r"Nemotron\s+[\d.]+\s+\S+\s+([+-][\d.]+)\s+\[\s*([+-][\d.]+),\s*([+-][\d.]+)\]",so)
put("StrongNemoLo",m.group(2)); put("StrongNemoHi",m.group(3))
put("StrongSignN","3"); put("StrongSignCells","4")
with open("paper/auto_v73.tex","w") as f:
    f.write("% Generated by scripts/gen_v73_numbers_v1.py -- do not edit by hand.\n")
    for k,v in M.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
print(open("paper/auto_v73.tex").read())
