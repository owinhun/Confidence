#!/usr/bin/env python3
"""The cascade table, emitted as a LaTeX macro from the data.

The v8 table was typed by hand. Its `omit` column turned out to be order-averaged while `claim`
and `+conf` came from a single order -- the swapped cascade runs did not exist -- so the three
columns were not on the same footing and the row deltas did not reconcile with the columns a
reader could see. That is the second hand-typed table in this project to be wrong. Every number
in the cascade table now comes from here.

Order-averaging is applied wherever both orders exist and the row is marked otherwise, so a
missing swap is visible in the output instead of silently changing what a column means.
"""

from __future__ import annotations

import json
import os

import numpy as np

CELLS = [("Qwen2.5-Omni", "s2"), ("Qwen3-Omni", "s2q3"), ("Qwen2-Audio", "nm_qwen2audio"),
         ("Audio-Flamingo-3", "nm_af3"), ("Nemotron/sound", "nm_nemotron")]
CONDS = ["none", "cascade_bare", "cascade_conf", "cascade_mono", "cascade_pct"]
BOOTS = 2000
MACRO = "paper/auto_cascade.tex"


def L(name):
    p = f"outputs/{name}_v1.jsonl"
    if not os.path.exists(p):
        return None
    d = {}
    for line in open(p):
        if line.strip():
            r = json.loads(line)
            d[r["clip"]] = r
    return d if len(d) >= 400 else None


def video(clip):
    return clip.split("/")[-1].split("_")[0]


def cell(pfx):
    """Accuracy per condition, order-averaged where both orders exist."""
    orders = []
    for tag in ("", "_swap"):
        got = {c: L(f"{pfx}_sound_{c}{tag}") for c in CONDS}
        if got["none"] is None or got["cascade_bare"] is None:
            continue
        have = [c for c in CONDS if got[c] is not None]
        ks = sorted(set.intersection(*(set(got[c]) for c in have)))
        orders.append(({c: got[c] for c in have}, ks))
    if not orders:
        return None
    common = set(CONDS)
    for got, _ in orders:
        common &= set(got)
    acc = {}
    for c in sorted(common, key=CONDS.index):
        acc[c] = float(np.mean([np.mean([got[c][k]["correct"] for k in ks])
                                for got, ks in orders]) * 100)
    return acc, len(orders), orders


def pistar(pfx):
    """Break-even precision from the controlled branches, order-averaged like the rest."""
    vals = []
    for tag in ("", "_swap"):
        b, T, F = (L(f"{pfx}_sound_none{tag}"), L(f"{pfx}_sound_true_high{tag}"),
                   L(f"{pfx}_sound_anon_high{tag}"))
        if any(x is None for x in (b, T, F)):
            continue
        ks = sorted(set(b) & set(T) & set(F))
        a0 = np.mean([b[k]["correct"] for k in ks])
        gt = np.mean([T[k]["correct"] for k in ks]) - a0
        gf = np.mean([F[k]["correct"] for k in ks]) - a0
        vals.append((gt, gf))
    if not vals:
        return None
    gt = float(np.mean([v[0] for v in vals]))
    gf = float(np.mean([v[1] for v in vals]))
    if gt <= 0:
        return "dagger"
    v = -gf / (gt - gf)
    return v if 0 < v < 1 else "dagger"


def fmt(x):
    return "--" if x is None else f"{x:.1f}"


if __name__ == "__main__":
    rows, notes = [], []
    for name, pfx in CELLS:
        r = cell(pfx)
        if r is None:
            notes.append(f"{name}: no data")
            continue
        acc, n_orders, _ = r
        pi = pistar(pfx)
        get = lambda c: acc.get(c)
        d_claim = (get("cascade_bare") - get("none")) if get("cascade_bare") is not None else None
        d_conf = (get("cascade_conf") - get("cascade_bare")) if get("cascade_conf") is not None else None
        pis = ("$\\dagger$" if pi == "dagger" else "--" if pi is None else f"${pi:.2f}$")
        mark = "" if n_orders == 2 else "$^{u}$"
        cells = " & ".join(fmt(get(c)) for c in CONDS)
        dd = " & ".join(("--" if d is None else f"${d:+.1f}$") for d in (d_claim, d_conf))
        rows.append(f"{name}{mark} & {cells} & {dd} & {pis} \\\\")
        notes.append(f"{name:18} orders={n_orders}  " +
                     "  ".join(f"{c}={fmt(get(c))}" for c in CONDS))

    open(MACRO, "w").write(
        "% Generated by scripts/gen_cascade_table_v1.py -- do not edit by hand.\n"
        "% The v8 table was typed by hand and mixed an order-averaged baseline with\n"
        "% single-order cascade columns. Nothing here is typed.\n"
        "\\newcommand{\\TabCascade}{%\n" + "\n".join(rows) + "\n}\n")
    print(f"{MACRO} 작성")
    print("  u 표시 = 아직 한 순서만 존재 (swap 실행 대기)\n")
    for n in notes:
        print("  " + n)
