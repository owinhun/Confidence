#!/usr/bin/env python3
"""Seed-robustness judgment for the error-repair sweep (wave21, pre-registered).

Same estimand and bootstrap as analyse_sweep_v1; the mix conditions carry a seed suffix
(s1/s2) passed as argv[1]. Endpoints are seed-free and reused unchanged.

Estimand, cells, bootstrap and the two predictions are fixed in outputs/log_v1.md. Endpoints
reuse existing runs: pi=0.748 is the real detector (cascadex_plain), pi=1.0 the bare true
claim. Each cell also gets its own bare break-even from the measured true/false branches, so
the predicted crossing is compared against the sweep bracket that actually contains it.
"""
import json, os, sys, pathlib
sys.path.insert(0, "scripts")
import numpy as np
import analyse_cascade_v2 as C

SEED = sys.argv[1] if len(sys.argv) > 1 else "s1"

CELLS = [("Qwen2.5", "s2"), ("Qwen3", "s2q3"), ("Qwen2-Audio", "nm_qwen2audio"),
         ("Nemotron", "nm_nemotron")]
LEVELS = [("0.748", "cascadex_plain"), ("0.80", f"cascademix80{SEED}_plain"),
          ("0.85", f"cascademix85{SEED}_plain"), ("0.90", f"cascademix90{SEED}_plain"),
          ("0.95", f"cascademix95{SEED}_plain"), ("1.0", "bare_true")]


def delta(pfx, cond):
    per, keys = [], []
    for sfx in ("", "_swap"):
        A, B = C.L(f"{pfx}_sound_{cond}{sfx}"), C.L(f"{pfx}_sound_none{sfx}")
        if A is None or B is None:
            return None
        ks = sorted(set(A) & set(B))
        per.append(np.array([A[k]["correct"] - B[k]["correct"] for k in ks], float))
        keys.append(ks)
    pt = 100 * np.mean([d.mean() for d in per])
    vids = sorted({C.video(k) for ks in keys for k in ks})
    vi = {v: i for i, v in enumerate(vids)}
    buckets = [[np.where(np.array([vi[C.video(k)] for k in ks]) == i)[0]
                for i in range(len(vids))] for ks in keys]
    rng = np.random.default_rng(0)
    bs = []
    for _ in range(2000):
        sel = rng.integers(0, len(vids), len(vids))
        vals = []
        for d, bk in zip(per, buckets):
            idx = np.concatenate([bk[i] for i in sel if bk[i].size])
            vals.append(d[idx].mean())
        bs.append(100 * np.mean(vals))
    return pt, float(np.percentile(bs, 2.5)), float(np.percentile(bs, 97.5))


def bare_pistar(pfx):
    gts, gfs = [], []
    for sfx in ("", "_swap"):
        b = C.L(f"{pfx}_sound_none{sfx}")
        T = C.L(f"{pfx}_sound_bare_true{sfx}")
        F = C.L(f"{pfx}_sound_bare_false{sfx}")
        if None in (b, T, F):
            continue
        ks = sorted(set(b) & set(T) & set(F))
        a0 = np.mean([b[k]["correct"] for k in ks])
        gts.append(100 * (np.mean([T[k]["correct"] for k in ks]) - a0))
        gfs.append(100 * (np.mean([F[k]["correct"] for k in ks]) - a0))
    gt, gf = np.mean(gts), np.mean(gfs)
    return -gf / (gt - gf) if gt > gf else None


rows_tex = []
print(f"{'cell':12s} " + " ".join(f"{lv:>16s}" for lv, _ in LEVELS) + "   pi*_bare  판정")
mono_all, cross_all, falsified = True, True, []
for nm, pfx in CELLS:
    ds = [delta(pfx, cond) for _, cond in LEVELS]
    ps = bare_pistar(pfx)
    pts = [d[0] for d in ds]
    mono = all(a <= b + 0.75 for a, b in zip(pts, pts[1:]))  # 0.75pp = CI 폭 내 잡음 허용
    # 부호 교차 구간
    cross = None
    for i in range(len(pts) - 1):
        if pts[i] < 0 <= pts[i + 1]:
            cross = (LEVELS[i][0], LEVELS[i + 1][0])
    # 반증: pi*<=0.92 인데 Delta(0.95) CI 상한 < 0
    d95 = ds[4]
    fal = (ps is not None and ps <= 0.92 and d95[2] < 0)
    if fal:
        falsified.append(nm)
    mono_all &= mono; cross_all &= (cross is not None)
    print(f"{nm:12s} " + " ".join(f"{d[0]:+5.1f}[{d[1]:+.1f},{d[2]:+.1f}]" for d in ds)
          + f"   {ps:.3f}   mono={'Y' if mono else 'N'} cross={cross}")
    cells = " & ".join(f"${d[0]:+.1f}$" for d in ds)
    rows_tex.append(f"{nm.replace('Qwen2.5','Qwen2.5-Omni').replace('Qwen3','Qwen3-Omni')} & {cells} & {ps:.2f} \\\\")

import pathlib
pathlib.Path(f"/tmp/auto_sweep_{SEED}.tex").write_text(
    "% Generated by scripts/analyse_sweep_v1.py -- do not edit by hand.\n"
    "\\newcommand{\\SweepRows}{%\n" + "\n".join(rows_tex) + "\n}\n"
    f"\\newcommand{{\\SweepMonoN}}{{{sum(1 for _ in CELLS) if mono_all else 'CHECK'}}}\n")
print(f"\n판정: P1 단조성 {'전셀 성립' if mono_all else '위반 있음'}, "
      f"P2 부호교차 {'전셀 존재' if cross_all else '누락 있음'}, "
      f"반증셀: {falsified or '없음'}")
