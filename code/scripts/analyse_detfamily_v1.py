#!/usr/bin/env python3
"""Does the forwarding loss depend on CLAP, or on forwarding?

Sec. 7 runs two detectors, but both are CLAP checkpoints, so they test checkpoint sensitivity
rather than family sensitivity -- the objection the reviews actually raise. AST and PANNs cannot
answer it: they emit AudioSet labels while the manifest names classes the way VGGSound does, and
stem matching put "people eating apple" under "Applause".

An audio LLM is asked the query class verbatim, exactly as CLAP is, so no taxonomy mapping
enters. Qwen2-Audio's no-metadata pass already is that measurement, cross-fitted the same way
(out-of-fold 77.8%, against CLAP's 74.8%). Its own downstream cell is excluded: a model reading
back a claim it produced itself is not a cascade.
"""
from __future__ import annotations
import sys, pathlib
sys.path.insert(0, "scripts")
import analyse_cascade_v2 as C

CELLS = [("Qwen2.5", "s2"), ("Qwen3", "s2q3"), ("Nemotron", "nm_nemotron")]

if __name__ == "__main__":
    rows = []
    for nm, pfx in CELLS:
        r = C.paired(pfx, "cascade3x_plain", "none")
        if r:
            rows.append((nm, r))
            print(f"  {nm:12} {r[0]:+6.1f} [{r[1]:+5.1f},{r[2]:+5.1f}]  p={r[6]:.3f}")
    v = sorted(r[0] for _, r in rows)
    neg = [n for n, r in rows if r[2] < 0]
    print(f"\n  손실 {-v[-1]:.1f}--{-v[0]:.1f}점, CI가 0 아래 {len(neg)}/{len(rows)}셀")
    pathlib.Path("paper/auto_detfam.tex").write_text(
        "% Generated by scripts/analyse_detfamily_v1.py -- do not edit by hand.\n"
        f"\\newcommand{{\\FamMin}}{{{-v[-1]:.1f}}}\n"
        f"\\newcommand{{\\FamMax}}{{{-v[0]:.1f}}}\n"
        f"\\newcommand{{\\FamNegN}}{{{len(neg)}}}\n"
        f"\\newcommand{{\\FamCells}}{{{len(rows)}}}\n"
        # NOT computed here. 77.8 is Qwen2-Audio's out-of-fold accuracy after its decision rule
        # is cross-fitted per source-video fold exactly as CLAP's is (log_v1.md, 2026-08-25:
        # "OOF 77.8%, bands 59.2 -> 93.9, fully monotone"). Raw no-metadata accuracy is 77.0
        # (first order) / 86.0 (swap), so this number is NOT recoverable from Table 2 or Table 3.
        # Re-running this script re-emits the constant; it does not re-verify it.
        f"\\newcommand{{\\FamAcc}}{{77.8}}\n")
    print("paper/auto_detfam.tex 작성")
