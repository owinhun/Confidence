#!/usr/bin/env python3
"""Seed-robustness macros for the error-repair sweep (wave21).

Runs the per-seed judgment for s1 and s2, counts seed-cells whose sign-crossing bracket
matches the published seed-0 bracket, and identifies the exception. Emits paper/auto_seeds.tex.
"""
import subprocess, re, pathlib

BASE = {"Qwen2.5": ("0.90", "0.95"), "Qwen3": ("0.90", "0.95"),
        "Qwen2-Audio": ("0.80", "0.85"), "Nemotron": ("0.85", "0.90")}
PISTAR = {"Qwen2.5": "0.902"}

agree, total, exc = 0, 0, []
for seed in ("s1", "s2"):
    out = subprocess.run(["python3", "scripts/analyse_sweep_seed_v1.py", seed],
                         capture_output=True, text=True).stdout
    for line in out.splitlines():
        m = re.match(r"(Qwen2\.5|Qwen3|Qwen2-Audio|Nemotron)\s.*cross=\('([\d.]+)', '([\d.]+)'\)", line)
        if not m: continue
        total += 1
        cell, lo, hi = m.groups()
        if (lo, hi) == BASE[cell]: agree += 1
        else: exc.append((seed, cell, lo, hi))

assert total == 8, total
assert len(exc) == 1 and exc[0][1] == "Qwen2.5" and exc[0][3] == "0.90", exc
p = pathlib.Path("paper/auto_seeds.tex")
p.write_text(
    "% generated by scripts/gen_seed_macros_v1.py -- do not edit\n"
    f"\\newcommand{{\\SeedAgreeCells}}{{{agree}}}\n"
    f"\\newcommand{{\\SeedTotCells}}{{{total}}}\n"
    "\\newcommand{\\SeedExcBoundary}{0.90}\n"
    "\\newcommand{\\SeedExcPi}{0.902}\n")
print(p.read_text())
