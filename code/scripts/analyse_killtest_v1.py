#!/usr/bin/env python3
"""The kill test: does forwarding the detector's ACTUAL output as a plain sentence pay?

Everything the paper says about packaging so far is argued from our own true/false branches --
we set the claim's truth from the manifest, measured each branch, and combined them at an assumed
precision to get a break-even. That is a counterfactual. It predicts that bare forwarding does
not pay at this detector's accuracy, because four of the five bare break-evens sit above 0.748.

`cascade{DET}_plain` sends the detector's real decision, on the clips where it is really right
and really wrong, phrased as a plain sentence rather than a Source/Claim block. Comparing it to
omitting the tag settles the prediction with a measurement instead of an extrapolation. If bare
forwarding loses here too, the paper's recommendation stops depending on the mixture assumption.

Reuses analyse_cascade_v2's loaders so the clip set, the source-video bootstrap and the
order-averaging are identical to Table 4 -- a second implementation is how the last two
contradictions between a table and its prose got in.
"""
from __future__ import annotations
import pathlib, sys
sys.path.insert(0, "scripts")
import analyse_cascade_v2 as C

CELLS = [("Qwen2.5-Omni", "s2"), ("Qwen3-Omni", "s2q3"), ("Qwen2-Audio", "nm_qwen2audio"),
         ("Audio Flamingo 3", "nm_af3"), ("Nemotron/sound", "nm_nemotron")]


def run(det):
    plain, bare = f"cascade{det}_plain", f"cascade{det}_bare"
    rows, notes, dplain = [], [], []
    for name, pfx in CELLS:
        dp = C.paired(pfx, plain, "none")      # plain sentence vs omitting
        db = C.paired(pfx, bare, "none")       # block format vs omitting
        dd = C.paired(pfx, plain, bare)        # plain vs block, same claim content
        if dp is None:
            notes.append(f"{name:18} plain 미완료"); continue
        dplain.append((name, dp))
        f = lambda r: "--" if r is None else f"${r[0]:+.1f}$ [{r[1]:+.1f},{r[2]:+.1f}]"
        rows.append(f"{name} & {f(dp)} & {f(db)} & {f(dd)} & {dp[3]} \\\\")
        notes.append(f"{name:18} plain-omit {dp[0]:+.2f} CI[{dp[1]:+.2f},{dp[2]:+.2f}] "
                     f"p={dp[6]:.3f} n={dp[3]}")
    return rows, notes, dplain


if __name__ == "__main__":
    det = sys.argv[1] if len(sys.argv) > 1 else "x"
    rows, notes, dplain = run(det)
    print(f"=== kill test, detector {det} ===")
    for n in notes:
        print("  " + n)
    if dplain:
        v = sorted(r[0] for _, r in dplain)
        neg = [n for n, r in dplain if r[2] < 0]      # CI entirely below zero -> real loss
        pos = [n for n, r in dplain if r[1] > 0]
        print(f"\n  완료 {len(dplain)}셀: plain-omit 범위 {v[0]:+.1f}..{v[-1]:+.1f}")
        print(f"  CI가 0 아래: {len(neg)}셀 {neg}")
        print(f"  CI가 0 위  : {len(pos)}셀 {pos}")
        # AF3 is the order-sensitive cell; the headline counts the order-robust ones, the same
        # split Table 4 and Figure 1 use, so the prose cannot quote a range AF3 sets
        prim = [(n, r) for n, r in dplain if "Flamingo" not in n]
        pv = sorted(r[0] for _, r in prim)
        pneg = [n for n, r in prim if r[2] < 0]
        m = pathlib.Path(f"paper/auto_kill{'' if det=='x' else '2'}.tex")
        m.write_text("% Generated by scripts/analyse_killtest_v1.py -- do not edit by hand.\n"
                     + f"\\newcommand{{\\KillMin{'' if det=='x' else 'B'}}}{{{-pv[-1]:.1f}}}\n"
                     + f"\\newcommand{{\\KillMax{'' if det=='x' else 'B'}}}{{{-pv[0]:.1f}}}\n"
                     + f"\\newcommand{{\\KillNegN{'' if det=='x' else 'B'}}}{{{len(pneg)}}}\n"
                     + f"\\newcommand{{\\KillCells{'' if det=='x' else 'B'}}}{{{len(prim)}}}\n")
        print(f"{m} 작성: 손실 {-pv[-1]:.1f}--{-pv[0]:.1f}, CI<0 {len(pneg)}/{len(prim)}")
