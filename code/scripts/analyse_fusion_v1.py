#!/usr/bin/env python3
"""Calibrated late fusion of detector confidence with the reader's own logit.

The standing systems objection: the paper compares no-tag against TEXT serialisations only,
when the classical alternative is score-level fusion. That baseline needs no new inference:
the reader's answer margin (from p_A of the no-metadata pass) and the detector's cross-fitted
calibrated q exist per clip. Fuse on the truth-aligned margin scale,

    m_fused = m_reader + lambda * s * logit(q),   s = +1 if the detector asserts the
                                                  correct side, else -1  (i.e. detector
                                                  evidence mapped to the truth axis)

with lambda chosen on the four training folds and evaluated on the held-out fold, exactly
mirroring the detector's own cross-fitting. Order-averaged over both answer orders.
"""
import json, os, sys
sys.path.insert(0, "scripts")
import numpy as np
import analyse_cascade_v2 as C

DET = {json.loads(l)["clip"]: json.loads(l) for l in open("outputs/clapx_cascade_v1.jsonl") if l.strip()}
CELLS = [("Qwen2.5", "s2"), ("Qwen3", "s2q3"), ("Qwen2-Audio", "nm_qwen2audio"), ("Nemotron", "nm_nemotron")]
LAMS = [0.0, 0.25, 0.5, 1.0, 2.0, 4.0]
EPS = 1e-6


def margins(pfx, sw):
    d = C.L(f"{pfx}_sound_none{'_swap' if sw else ''}")
    out = {}
    for k, r in d.items():
        pa = min(max(r["p_A"], EPS), 1 - EPS)
        m = np.log(pa) - np.log(1 - pa)
        m = m if r["label"] == "A" else -m
        out[k] = (m if not sw else -m, r["label"])
    return out


def run(pfx):
    accs = {}
    for sw in (False, True):
        M = margins(pfx, sw)
        ks = sorted(set(M) & set(DET))
        folds = np.array([DET[k]["fold"] for k in ks])
        m = np.array([M[k][0] for k in ks])
        lab = [M[k][1] for k in ks]
        q = np.array([min(max(DET[k]["q"], EPS), 1 - EPS) for k in ks])
        s = np.array([1 if DET[k]["det_pred"] == lab[i] else -1 for i, k in enumerate(ks)])
        ev = s * (np.log(q) - np.log(1 - q))
        acc_f = np.zeros(len(ks))
        for f in sorted(set(folds)):
            tr, te = folds != f, folds == f
            best = max(LAMS, key=lambda L: ((m[tr] + L * ev[tr]) > 0).mean())
            acc_f[te] = ((m[te] + best * ev[te]) > 0)
        accs[sw] = (100 * acc_f.mean(), 100 * (m > 0).mean())
    fu = 0.5 * (accs[False][0] + accs[True][0])
    base = 0.5 * (accs[False][1] + accs[True][1])
    return base, fu


rows = []
for nm, pfx in CELLS:
    base, fu = run(pfx)
    rows.append((nm, base, fu, fu - base))
    print(f"  {nm:12s} omit(margin) {base:5.1f}  +fusion {fu:5.1f}  Δ {fu-base:+.2f}")
import pathlib
pathlib.Path("paper/auto_fusion.tex").write_text(
    "% Generated by scripts/analyse_fusion_v1.py -- do not edit by hand.\n"
    f"\\newcommand{{\\FuseGainMin}}{{{min(r[3] for r in rows):+.1f}}}\n"
    f"\\newcommand{{\\FuseGainMax}}{{{max(r[3] for r in rows):+.1f}}}\n"
    f"\\newcommand{{\\FuseCells}}{{{len(rows)}}}\n"
    f"\\newcommand{{\\FusePosN}}{{{sum(1 for r in rows if r[3] > 0)}}}\n")
print("paper/auto_fusion.tex 작성")
