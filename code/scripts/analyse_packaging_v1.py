#!/usr/bin/env python3
"""Does the Source/Claim block damp the model's response to the claim, in both directions?

The v11 draft told the packaging result as "bare helps, block hurts". That reading came from a
broken condition -- detclaim_* asserted the A-side proposition regardless of the label, so both
branches were 50% true -- and it did not survive the fix. What the corrected data shows is not a
sign flip but a contraction: the block moves the model less than the plain sentence does, on the
true claim AND on the false one.

That is the same shape as the numeric-versus-verbal result, where writing the confidence as a
number compresses the model's response to the verbal ladder. Reporting both as compression, with
the same statistic, is stronger than reporting them as two unrelated packaging quirks -- and it
is what the numbers actually say.

The statistic is the true-minus-false span: how far apart the two claim directions push accuracy.
Compression is span_block / span_bare, bootstrapped over source videos so the CI accounts for the
clip clustering the same way Table 4 does.
"""
from __future__ import annotations
import sys, pathlib
sys.path.insert(0, "scripts")
import numpy as np
import analyse_cascade_v2 as C

CELLS = [("Qwen2.5", "s2"), ("Qwen3", "s2q3"), ("Qwen2-Audio", "nm_qwen2audio"),
         ("AF3", "nm_af3"), ("Nemotron", "nm_nemotron")]
BOOTS = 2000


def span_ratio(pfx, attr="sound"):
    """(bare span, block span, ratio) with a source-video bootstrap CI on the ratio."""
    conds = ["none", "bare_true", "bare_false", "detclaim_true", "detclaim_false"]
    os_ = []
    for tag in ("", "_swap"):
        got = {c: C.L(f"{pfx}_{attr}_{c}{tag}") for c in conds}
        if any(v is None for v in got.values()):
            continue
        ks = sorted(set.intersection(*(set(v) for v in got.values())))
        os_.append((got, ks))
    if not os_:
        return None

    def spans(got, ks, idx=None):
        sel = ks if idx is None else [ks[i] for i in idx]
        a = lambda c: np.mean([got[c][k]["correct"] for k in sel])
        return ((a("bare_true") - a("bare_false")) * 100,
                (a("detclaim_true") - a("detclaim_false")) * 100)

    pt = np.mean([spans(g, k) for g, k in os_], axis=0)
    vids = sorted({C.video(k) for g, k in os_ for k in k})
    vi = {v: i for i, v in enumerate(vids)}
    buckets = [[np.where(np.array([vi[C.video(k)] for k in ks]) == i)[0]
                for i in range(len(vids))] for _, ks in os_]
    rng = np.random.default_rng(0)
    rs = []
    for _ in range(BOOTS):
        sel = rng.integers(0, len(vids), len(vids))
        vals = []
        for (g, ks), bk in zip(os_, buckets):
            idx = np.concatenate([bk[i] for i in sel if bk[i].size])
            if idx.size:
                vals.append(spans(g, ks, idx))
        if vals:
            b, k_ = np.mean(vals, axis=0)
            if b > 0:
                rs.append(k_ / b * 100)
    return float(pt[0]), float(pt[1]), float(pt[1] / pt[0] * 100), \
        float(np.percentile(rs, 2.5)), float(np.percentile(rs, 97.5))


if __name__ == "__main__":
    attr = sys.argv[1] if len(sys.argv) > 1 else "sound"
    out, notes = [], []
    print(f"=== 블록 포장이 주장 반응을 압축하는가 ({attr}) ===")
    print(f"{'셀':13} {'bare span':>10} {'block span':>11} {'압축률':>8} {'95% CI':>16}")
    for nm, pfx in CELLS:
        r = span_ratio(pfx, attr)
        if r is None:
            notes.append(f"{nm}: 미완"); continue
        b, k, ratio, lo, hi = r
        print(f"{nm:13} {b:10.1f} {k:11.1f} {ratio:7.0f}% {f'[{lo:.0f},{hi:.0f}]':>16}")
        out.append((nm, ratio, lo, hi))
    for n in notes:
        print("  " + n)
    if out:
        rs = sorted(x[1] for x in out)
        below = [x[0] for x in out if x[3] < 100]
        print(f"\n압축률 범위 {rs[0]:.0f}--{rs[-1]:.0f}%, 중앙값 {rs[len(rs)//2]:.0f}%")
        print(f"CI가 100% 아래(압축 확정): {len(below)}/{len(out)}셀 {below}")
        m = pathlib.Path(f"paper/auto_pack{'' if attr=='sound' else '_'+attr}.tex")
        # AF3 is the order-sensitive cell; a claim worded "in all N cells" must not silently
        # include it when the abstract reports it separately.
        prim = [x for x in out if x[0] != "AF3"]
        prs = sorted(x[1] for x in prim)
        pbelow = [x[0] for x in prim if x[3] < 100]
        m.write_text("% Generated by scripts/analyse_packaging_v1.py -- do not edit by hand.\n"
                     + f"\\newcommand{{\\PackMin}}{{{rs[0]:.0f}}}\n"
                     + f"\\newcommand{{\\PackMax}}{{{rs[-1]:.0f}}}\n"
                     + f"\\newcommand{{\\PackMed}}{{{rs[len(rs)//2]:.0f}}}\n"
                     + f"\\newcommand{{\\PackBelowN}}{{{len(below)}}}\n"
                     + f"\\newcommand{{\\PackCells}}{{{len(out)}}}\n"
                     + f"\\newcommand{{\\PackPrimMin}}{{{prs[0]:.0f}}}\n"
                     + f"\\newcommand{{\\PackPrimMax}}{{{prs[-1]:.0f}}}\n"
                     + f"\\newcommand{{\\PackPrimMed}}{{{prs[len(prs)//2]:.0f}}}\n"
                     + f"\\newcommand{{\\PackPrimBelowN}}{{{len(pbelow)}}}\n"
                     + f"\\newcommand{{\\PackPrimCells}}{{{len(prim)}}}\n")
        print(f"{m} 작성")
