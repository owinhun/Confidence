#!/usr/bin/env python3
"""Presence-aligned shift under each field, on the same ten cells as analyse_prior_v1.py.

A reviewer raised the sharpest identification objection of the review rounds: Prior: high says
the CLASS is common in general, so it should push toward "yes" for true and false claims alike,
and a shift common to both branches cancels in beta by construction. If that were what is
happening, Prior's small beta would show only that Prior is not claim-aligned -- not that Prior
moves the model less -- and the paper's gloss would be over-read.

No new inference is needed. Define the presence-aligned log-odds

    u = log p(yes) - log p(no),

which is +logit(p_A) in the prespecified order and -logit(p_A) under the swap, because the swap
exchanges the option letters. Compare each field's high-minus-low change in u, order-averaged,
on the same false-claim block and the same items. Same cell list as analyse_prior_v1.py, so the
denominator the paper already quotes does not change.
"""
from __future__ import annotations
import json, os, pathlib, sys
import numpy as np
sys.path.insert(0, "scripts")
from analyse_prior_v1 import CELLS

EPS = 1e-6


def L(n):
    p = f"outputs/{n}_v1.jsonl"
    if not os.path.exists(p):
        return None
    d = {}
    for line in open(p):
        if line.strip():
            r = json.loads(line)
            d[r["clip"]] = r
    return d if len(d) >= 300 else None


def u_of(r, swapped):
    pa = min(max(r["p_A"], EPS), 1 - EPS)
    v = np.log(pa) - np.log(1 - pa)
    return -v if swapped else v


def shift(pfx, attr, hi, lo):
    out = []
    for tag in ("", "_swap"):
        sw = tag == "_swap"
        H, Lo = L(f"{pfx}_{attr}_{hi}{tag}"), L(f"{pfx}_{attr}_{lo}{tag}")
        if H is None or Lo is None:
            return None
        ks = sorted(set(H) & set(Lo))
        if len(ks) < 100:
            return None
        out.append(np.mean([u_of(H[k], sw) - u_of(Lo[k], sw) for k in ks]))
    return float(np.mean(out)) if out else None


if __name__ == "__main__":
    print(f"{'cell':18}{'du Confidence':>15}{'du Priority':>13}{'du Prior':>10}")
    rows = []
    for name, pfx, attr in CELLS:
        c = shift(pfx, attr, "anon_high", "anon_low")
        p = shift(pfx, attr, "priority_high", "priority_low")
        r = shift(pfx, attr, "prior_high", "prior_low")
        if None in (c, p, r):
            print(f"{name:18}데이터 부족"); continue
        rows.append((name, c, p, r))
        print(f"{name:18}{c:15.3f}{p:13.3f}{r:10.3f}")
    a = np.array([[r[1], r[2], r[3]] for r in rows])
    cm, pm, rm = (np.abs(a[:, i]).mean() for i in range(3))
    npos = int((a[:, 2] > 0).sum())
    nbig = int((np.abs(a[:, 2]) > np.abs(a[:, 0])).sum())
    print(f"\n  mean |du|  Confidence {cm:.2f}  Priority {pm:.2f}  Prior {rm:.2f}"
          f"   (n={len(rows)} cells)")
    print(f"  Prior toward presence in {npos}/{len(rows)}; |Prior|>|Confidence| in {nbig}/{len(rows)}")
    pathlib.Path("paper/auto_v81.tex").write_text(
        "% Generated by scripts/gen_v81_prior_presence_v1.py -- do not edit by hand.\n"
        f"\\newcommand{{\\PresConf}}{{{cm:.2f}}}\n"
        f"\\newcommand{{\\PresPrio}}{{{pm:.2f}}}\n"
        f"\\newcommand{{\\PresPrior}}{{{rm:.2f}}}\n"
        f"\\newcommand{{\\PresCells}}{{{len(rows)}}}\n"
        f"\\newcommand{{\\PresPriorPosN}}{{{npos}}}\n"
        f"\\newcommand{{\\PresPriorBigN}}{{{nbig}}}\n")
    print("  paper/auto_v81.tex 작성")
