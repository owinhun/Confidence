#!/usr/bin/env python3
"""Does gating on the detector's own confidence make forwarding pay?

Reviews of v32 raised the same systems objection twice: showing that *unconditional* forwarding
hurts is close to arithmetic, because the detector is less accurate than the downstream model.
The policy a designer would actually write is conditional -- forward the tag only when the
detector is confident about it, otherwise send nothing. If that policy beats omitting, the
paper's practical claim is much weaker; if it does not, the claim is much stronger.

Nothing new has to be run. The cascade files already carry, per clip, the cross-fitted decision
`det_pred` and its isotonic-calibrated confidence `q`, and both the forwarded and the omitted
downstream outcomes exist for every clip. A gate is therefore a per-clip choice between two
numbers we already have.

The threshold is chosen ON THE TEST DATA, by sweeping every observed value of q and keeping the
best. That is not a policy anyone could deploy -- it is an upper bound on what any threshold
could achieve, which is the only honest way to make a negative result convincing. Reported the
same way as everything else: order-averaged over both answer orders, bootstrapped over source
videos.
"""
from __future__ import annotations
import json, sys
sys.path.insert(0, "scripts")
import numpy as np
import analyse_cascade_v2 as C

# name -> (per-clip detector file, the downstream condition that forwards that detector)
DETS = [("CLAP", "outputs/clapx_cascade_v1.jsonl", "cascadex_plain"),
        ("CLAP-2", "outputs/clap2x_cascade_v1.jsonl", "cascade2x_plain"),
        ("Qwen2-Audio", "outputs/q2ax_cascade_v1.jsonl", "cascade3x_plain")]
CELLS = [("Qwen2.5", "s2"), ("Qwen3", "s2q3"),
         ("Qwen2-Audio", "nm_qwen2audio"), ("Nemotron", "nm_nemotron")]


def gate(pfx, cond, det):
    """Best achievable gain of a q-threshold gate over omitting, and its bootstrap interval."""
    O = [C.L(f"{pfx}_sound_none{s}") for s in ("", "_swap")]
    F = [C.L(f"{pfx}_sound_{cond}{s}") for s in ("", "_swap")]
    if any(x is None for x in O + F):
        return None
    ks = sorted(set(O[0]) & set(F[0]) & set(det))
    o = np.array([np.mean([x[k]["correct"] for x in O]) for k in ks])
    f = np.array([np.mean([x[k]["correct"] for x in F]) for k in ks])
    q = np.array([det[k]["q"] for k in ks])
    # the policy space has to contain "forward nothing" (a threshold above every observed q),
    # otherwise the best gate can come out negative and the upper bound is not an upper bound
    taus = np.append(np.unique(np.round(q, 4)), q.max() + 1e-6)
    gains = np.array([100 * (np.where(q >= t, f, o) - o).mean() for t in taus])
    t = taus[int(np.argmax(gains))]
    vids = np.array([C.video(k) for k in ks])
    uv = sorted(set(vids)); idx = {v: np.where(vids == v)[0] for v in uv}
    rng = np.random.default_rng(0)
    bs = []
    for _ in range(4000):
        pick = np.concatenate([idx[uv[i]] for i in rng.integers(0, len(uv), len(uv))])
        bs.append(100 * (np.where(q[pick] >= t, f[pick], o[pick]) - o[pick]).mean())
    lo, hi = np.percentile(bs, [2.5, 97.5])
    # a gate that forwards nothing is the omit policy itself
    return dict(gain=gains.max(), lo=lo, hi=hi, tau=t,
                frac=100 * (q >= t).mean(), omit=100 * o.mean(), fwd=100 * f.mean())


def main():
    rows = []
    for dn, dfile, cond in DETS:
        det = {json.loads(l)["clip"]: json.loads(l) for l in open(dfile) if l.strip()}
        dacc = 100 * np.mean([r["det_pred"] == r["label"] for r in det.values()])
        for cn, pfx in CELLS:
            r = gate(pfx, cond, det)
            if r is None:
                continue
            r.update(det=dn, cell=cn, dacc=dacc)
            rows.append(r)
            print(f"{dn:12s} {cn:12s} omit {r['omit']:5.1f}  forward {r['fwd']:5.1f}  "
                  f"gate +{r['gain']:.2f} [{r['lo']:+.2f},{r['hi']:+.2f}] "
                  f"tau={r['tau']:.3f} sends {r['frac']:.0f}%")

    nothing = [r for r in rows if r["frac"] == 0 or r["gain"] == 0]
    crossing = [r for r in rows if r["lo"] > 0]
    losses = [r["omit"] - r["fwd"] for r in rows]
    print(f"\n{len(rows)} (detector, cell) pairs; best gate gain {max(r['gain'] for r in rows):.2f} pts, "
          f"{len(crossing)} with interval above zero; unconditional forwarding costs "
          f"{min(losses):.1f}--{max(losses):.1f}")

    import pathlib
    pathlib.Path("paper/auto_sel.tex").write_text(
        "% Generated by scripts/analyse_selective_v1.py -- do not edit by hand.\n"
        f"\\newcommand{{\\SelPairs}}{{{len(rows)}}}\n"
        f"\\newcommand{{\\SelDetN}}{{{len({r['det'] for r in rows})}}}\n"
        f"\\newcommand{{\\SelGainMax}}{{{max(r['gain'] for r in rows):.2f}}}\n"
        f"\\newcommand{{\\SelSigN}}{{{len(crossing)}}}\n"
        f"\\newcommand{{\\SelNothingN}}{{{len(nothing)}}}\n"
        f"\\newcommand{{\\SelFwdLossMin}}{{{min(losses):.1f}}}\n"
        f"\\newcommand{{\\SelFwdLossMax}}{{{max(losses):.1f}}}\n")
    print("paper/auto_sel.tex 작성")


if __name__ == "__main__":
    main()
