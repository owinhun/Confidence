#!/usr/bin/env python3
"""v77 macros. Two independent mock reviews of v75 raised the same defect: the conclusion's policy
recommendation does not match Tables 4 and 5.

Reconstructing absolute accuracy from Table 4 (plain and in-block are deltas against omitting;
verbal and numeric are deltas against the block) shows three things the conclusion glossed over:
  * omitting beats every forwarding policy in all five cells at this detector's accuracy;
  * a numeric field beats the block WITHOUT a field in only one order-robust cell, and loses in two
    -- "numeric costs less than verbal" is true, "add numeric" is not;
  * on Audio Flamingo 3 the block is far worse than the plain sentence, the opposite of the others.
Break-evens are also policy-specific: Table 5's are bare-sentence, Table 4's in-block, and two of
the latter exceed one. All of these are emitted as macros so the prose cannot drift from the table.
"""
import re, pathlib
P = pathlib.Path("paper")
def macros(*names):
    d = {}
    for n in names:
        t = (P / n).read_text()
        for k, v in re.findall(r"\\newcommand\{\\(\w+)\}\{([^{}]*)\}", t): d[k] = v
        for k, v in re.findall(r"\\newcommand\{\\(\w+)\}\{%\n(.*?)\n\}", t, re.S): d[k] = v
    return d
def cells(row): return [c.strip().strip("$") for c in row.rstrip("\\ ").split("&")]
M = macros("auto_cascade.tex", "auto_swing.tex")
rows = []
for r in M["TabCascade"].strip().splitlines():
    c = cells(r)
    name = c[0].replace("$^{s}$", "").replace("^{s}", "")
    omit, plain, inblk, verb, num = float(c[1]), float(c[2]), float(c[4]), float(c[5]), float(c[6])
    rows.append(dict(name=name, omit=omit, plain=omit + plain, block=omit + inblk,
                     bv=omit + inblk + verb, bn=omit + inblk + num,
                     num_minus_block=num, block_minus_plain=inblk - plain))
prim = [r for r in rows if "Flamingo" not in r["name"]]
omit_best = sum(1 for r in rows if r["omit"] >= max(r["plain"], r["block"], r["bv"], r["bn"]))
af3 = next(r for r in rows if "Flamingo" in r["name"])
# Smallest unaided accuracy among the admitted headline cells, from Table 3. The sensitivity row
# (Audio Flamingo 3, marked $^{s}$) must be excluded: it is the cell that fails order-robustness,
# so quoting its 77.8 as the floor of the admitted set contradicted the very next clause, which
# says the one cell below that floor failed order-robustness. Order-robust floor is 81.5.
import re as _re
a0s = [float(_re.match(r"[\d.]+", cells(r)[2]).group(0))
       for r in M["HeadRows"].strip().splitlines() if "^{s}" not in cells(r)[0]]
out = {
    "NumOverBlockN": str(sum(1 for r in prim if r["num_minus_block"] > 0)),
    "NumUnderBlockN": str(sum(1 for r in prim if r["num_minus_block"] < 0)),
    "NumBlockCells": str(len(prim)),
    "OmitBestN": str(omit_best),
    "OmitCells": str(len(rows)),
    "AFBlockGap": f"{abs(af3['block_minus_plain']):.1f}",
    "AdmitMinAZero": f"{min(a0s):.1f}",
}
with open(P / "auto_v77.tex", "w") as f:
    f.write("% Generated by scripts/gen_v77_numbers_v1.py -- do not edit by hand.\n")
    for k, v in out.items(): f.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
for r in rows:
    print(f"  {r['name']:18} omit {r['omit']:.1f}  plain {r['plain']:.1f}  block {r['block']:.1f}  "
          f"blk+num {r['bn']:.1f}   num-block {r['num_minus_block']:+.1f}")
print(open(P / "auto_v77.tex").read())
