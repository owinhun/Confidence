#!/usr/bin/env python3
"""The full eligibility flow, one row per cell per answer order.

The Protocol quoted four counts (18 floor, 4 recall, 5 ceiling, 5 eligible) that did not
reconcile with the tables: Qwen2.5/sound and Qwen3/sound sit at 95.25% and 95.50%, above the
0.95 bound, and Figure 1 calls them ceiling cells, but the flow counted only the four greyscale
cells as ceiling. The counts were also taken in one answer order while the gate is claimed to
apply to both.

Emitting the whole grid removes the arithmetic question. Status is computed per order; a cell's
verdict is the pair, and only cells eligible-or-ceiling in BOTH orders are treated as primary.
"""

from __future__ import annotations

import json
import os
import pathlib
from collections import Counter

import numpy as np

MODELS = [("Qwen2.5", "s2"), ("Qwen3", "s2q3"), ("VideoLLaMA2.1", "s2vl"),
          ("Qwen2-Audio", "nm_qwen2audio"), ("AF3", "nm_af3"),
          ("Nemotron", "nm_nemotron"), ("Phi-4-mm", "nm_phi4mm")]
ATTRS = ["sound", "colour", "noise", "lowpass", "reverb", "silence"] + \
        [f"grad_{a}_{g}" for a in ("noise", "lowpass", "reverb") for g in ("g1","g2","g3","g4")]


def L(name):
    p = f"outputs/{name}_v1.jsonl"
    if not os.path.exists(p):
        return None
    d = {}
    for line in open(p):
        if line.strip():
            r = json.loads(line)
            d[r["clip"]] = r
    return d if len(d) >= 400 else None


def status(b):
    acc = float(np.mean([r["correct"] for r in b.values()]))
    rec = [float(np.mean([r["correct"] for r in b.values() if r["label"] == lb]))
           for lb in ("A", "B")]
    if acc < 0.60:
        return "floor", acc, rec
    if min(rec) < 0.60:
        return "one-sided", acc, rec
    if acc > 0.95:
        return "ceiling", acc, rec
    return "eligible", acc, rec


if __name__ == "__main__":
    grid, counts = [], Counter()
    for name, pfx in MODELS:
        for attr in ATTRS:
            got = {}
            for tag, lab in (("", "orig"), ("_swap", "swap")):
                b = L(f"{pfx}_{attr}_none{tag}")
                if b is not None:
                    got[lab] = status(b)
            if not got:
                continue
            grid.append((name, attr, got))
            counts[got["orig"][0] if "orig" in got else list(got.values())[0][0]] += 1

    print(f"{'model':14}{'attribute':16}{'orig A0':>9}{'orig rec':>10}{'orig':>11}"
          f"{'swap A0':>9}{'swap rec':>10}{'swap':>11}")
    both_ok = 0
    for name, attr, got in grid:
        def f(lab):
            if lab not in got:
                return f"{'--':>9}{'--':>10}{'--':>11}"
            st, acc, rec = got[lab]
            return f"{acc*100:9.1f}{f'{rec[0]*100:.0f}/{rec[1]*100:.0f}':>10}{st:>11}"
        ok = (len(got) == 2 and
              all(g[0] in ("eligible", "ceiling") for g in got.values()))
        both_ok += ok
        print(f"{name:14}{attr:16}{f('orig')}{f('swap')}{'  *' if ok else ''}")

    print(f"\ncells run: {len(grid)}   (* = eligible-or-ceiling in BOTH orders: {both_ok})")
    print("counted in the original order only, which is what the Protocol quoted:")
    for k in ("floor", "one-sided", "ceiling", "eligible"):
        print(f"  {k:11}{counts[k]:3}")
    n_swap = sum(1 for _, _, g in grid if "swap" in g)
    print(f"\ncells with a swapped pass: {n_swap} of {len(grid)}"
          f"  -- the rest have a single-order verdict only")
    rows = []
    for name, attr, got in grid:
        if len(got) != 2:
            continue
        o, s = got["orig"], got["swap"]
        rows.append(f"{name} & \\texttt{{{attr}}} & {o[1]*100:.1f} & {o[0]} & "
                    f"{s[1]*100:.1f} & {s[0]} \\\\")
    pathlib.Path("paper/auto_flow.tex").write_text(
        "% Generated by scripts/gen_flow_table_v1.py -- do not edit by hand.\n"
        "\\newcommand{\\TabFlow}{%\n" + "\n".join(rows) + "\n}\n")
    print(f"\npaper/auto_flow.tex: 양방향이 있는 {len(rows)}셀")
