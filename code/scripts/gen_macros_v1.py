#!/usr/bin/env python3
"""Every number the manuscript quotes, emitted as LaTeX macros from the data.

Two failures motivated this. A Nemotron row was once typed into a table by hand and turned out
to be invented; and after Nemotron was added, ranges like "Priority recovers 7--51%" stayed at
their five-cell values while the tables underneath moved to seven cells. Both are the same
fault: numbers reaching the PDF without passing through the data.

From here the body cites macros only. Re-running this file after any new condition lands
updates the abstract, the prose ranges, the table rows and the figure legend together, so they
cannot drift apart again.

Everything is order-averaged where both answer orders exist, because the swapped half is what
the paper uses to justify withdrawing a cell -- applying that standard to one table and not the
next is the inconsistency the reviews caught.
"""

from __future__ import annotations

import json
import os
from math import comb

import numpy as np

OUT = "outputs"
EPS = 1e-6
BOOTS = 1500
MACRO = "paper/auto_numbers.tex"

# display name, file prefix, attribute, backbone
CELLS = [("Qwen2.5-Omni", "s2", "sound", "Qwen2.5"),
         ("Qwen3-Omni", "s2q3", "sound", "Qwen3"),
         ("VideoLLaMA2.1", "s2vl", "colour", "Qwen2"),
         ("Qwen2-Audio", "nm_qwen2audio", "sound", "Qwen2"),
         ("Audio Flamingo 3", "nm_af3", "sound", "Qwen2"),
         ("Nemotron/sound", "nm_nemotron", "sound", "Nemotron-H"),
         ("Nemotron/colour", "nm_nemotron", "colour", "Nemotron-H")]


def L(name):
    p = f"{OUT}/{name}_v1.jsonl"
    if not os.path.exists(p):
        return None
    d = {}
    for line in open(p).read().splitlines():
        if line.strip():
            r = json.loads(line)
            d[r["clip"]] = r
    return d if len(d) >= 400 else None


def margin(rec, swapped):
    """Truth-aligned margin.

    p_A is the probability of *position* A. Under the swap position A is "No", so the semantic
    sign flips; the read-out already inverts `pred`, which is why override rates were unaffected
    and the margin was not.
    """
    pa = min(max(rec["p_A"], EPS), 1 - EPS)
    lo = np.log(pa) - np.log(1 - pa)
    v = lo if rec["label"] == "A" else -lo
    return -v if swapped else v


def video(clip):
    return clip.split("/")[-1].split("_")[0]


def contrast(pfx, attr, hi, lo, tag):
    sw = tag == "_swap"
    b, A, B = (L(f"{pfx}_{attr}_none{tag}"), L(f"{pfx}_{attr}_{hi}{tag}"),
               L(f"{pfx}_{attr}_{lo}{tag}"))
    if any(x is None for x in (b, A, B)):
        return None
    ks = [k for k in b if b[k]["correct"] and k in A and k in B]
    if len(ks) < 30:
        return None
    return float(np.mean([margin(A[k], sw) - margin(B[k], sw) for k in ks]))


def avg(pfx, attr, hi, lo):
    """Order-averaged contrast, falling back to the single order when no swap exists."""
    a, s = contrast(pfx, attr, hi, lo, ""), contrast(pfx, attr, hi, lo, "_swap")
    if a is None:
        return None
    return (a + s) / 2 if s is not None else a


def baseline(pfx, attr):
    """A_0 in each order and their mean, with the both-order gate verdict."""
    out = {}
    for tag in ("", "_swap"):
        b = L(f"{pfx}_{attr}_none{tag}")
        if b is None:
            out[tag] = None
            continue
        acc = np.mean([r["correct"] for r in b.values()])
        rec = [np.mean([r["correct"] for r in b.values() if r["label"] == Lb])
               for Lb in ("A", "B")]
        out[tag] = (float(acc), [float(x) for x in rec], sum(r["correct"] for r in b.values()))
    return out


def macro_esc(name):
    return "".join(c for c in name.title() if c.isalpha())


def fmt(x, nd=2, sign=True):
    if x is None:
        return "--"
    return f"{x:+.{nd}f}" if sign else f"{x:.{nd}f}"


if __name__ == "__main__":
    lines = ["% Generated by scripts/gen_macros_v1.py -- do not edit by hand.",
             "% Every figure quoted in the body comes from here, so a re-run keeps the",
             "% abstract, the prose and the tables consistent with each other.", ""]
    rows_steps, rows_field, ratios, prio_share, conf_share = [], [], [], [], []
    nonep_share = []

    for name, pfx, attr, bb in CELLS:
        base = baseline(pfx, attr)
        a0o = base.get("") and base[""][0]
        a0s = base.get("_swap") and base["_swap"][0]
        a0 = np.mean([x for x in (a0o, a0s) if x is not None]) if a0o is not None else None
        steps = [avg(pfx, attr, "null_block", "none"),
                 avg(pfx, attr, "srconly_high", "null_block"),
                 avg(pfx, attr, "priority_high", "srconly_high"),
                 avg(pfx, attr, "anon_high", "priority_high")]
        fields = [avg(pfx, attr, f"{p}_high", f"{p}_low")
                  for p in ("anon", "reliab", "certain", "prior",
                            "priority", "urgency", "opaque")]
        rows_steps.append((name, bb, a0, steps))
        rows_field.append((name, bb, fields))
        if steps[2] and steps[3]:
            conf_share.append(abs(steps[3] / steps[2]) * 100)
        if fields[0] and fields[4]:
            prio_share.append(abs(fields[4] / fields[0]) * 100)
        # PrioShare covers Priority alone, but the prose says "the non-epistemic ones",
        # meaning all three. Metric-X reaches 84% on one cell, outside the Priority-only
        # range, so the sentence was claiming more than the macro measured. Emit the range
        # over every non-epistemic name, and the count of cells that stay under half.
        for i in (4, 5, 6):
            if fields[0] and fields[i]:
                nonep_share.append(abs(fields[i] / fields[0]) * 100)

    def rng(xs, nd=1):
        xs = [x for x in xs if x is not None]
        return (f"{min(xs):.{nd}f}", f"{max(xs):.{nd}f}") if xs else ("--", "--")

    if nonep_share:
        lo_, hi_ = rng(nonep_share, 0)
        lines.append(f"\\newcommand{{\\NonEpShareMin}}{{{lo_}}}")
        lines.append(f"\\newcommand{{\\NonEpShareMax}}{{{hi_}}}")
        lines.append(f"\\newcommand{{\\NonEpShareN}}{{{len(nonep_share)}}}")
        lines.append(f"\\newcommand{{\\NonEpHalfN}}{{{sum(1 for v in nonep_share if v < 50)}}}")

    claim_vals = [abs(r[3][2]) for r in rows_steps if r[3][2] is not None]
    conf_hi = [abs(r[3][3]) for r in rows_steps if r[3][3] is not None]
    lo, hi = rng(claim_vals)
    lines += [f"\\newcommand{{\\ClaimMin}}{{{lo}}}", f"\\newcommand{{\\ClaimMax}}{{{hi}}}"]
    lo, hi = rng(conf_hi)
    lines += [f"\\newcommand{{\\ConfHighMin}}{{{lo}}}", f"\\newcommand{{\\ConfHighMax}}{{{hi}}}"]
    lo, hi = rng(conf_share, 0)
    lines += [f"\\newcommand{{\\ConfShareMin}}{{{lo}}}", f"\\newcommand{{\\ConfShareMax}}{{{hi}}}"]
    lo, hi = rng(prio_share, 0)
    lines += [f"\\newcommand{{\\PrioShareMin}}{{{lo}}}", f"\\newcommand{{\\PrioShareMax}}{{{hi}}}"]
    lines += [f"\\newcommand{{\\NumCells}}{{{len(CELLS)}}}",
              f"\\newcommand{{\\NumModels}}{{{len({c[1] for c in CELLS})}}}", ""]

    lines.append("% Table: one-step contrasts, order-averaged, at high")
    lines.append("\\newcommand{\\TabSteps}{%")
    for name, bb, a0, s in rows_steps:
        cells = " & ".join(f"${fmt(x)}$" if x is not None else "--" for x in s)
        lines.append(f"{name} & {bb} & {cells} \\\\")
    lines.append("}")
    lines.append("")
    lines.append("% Merged table: one-step contrasts | epistemic fields | non-epistemic fields")
    lines.append("\\newcommand{\\TabMerged}{%")
    for (name, bb, a0, st), (_n2, _b2, f_) in zip(rows_steps, rows_field):
        if "Flamingo" in name:
            name += "$^{s}$"
        left = " & ".join(f"${fmt(x)}$" if x is not None else "--" for x in st)
        epi = " & ".join(f"${fmt(x)}$" if x is not None else "--" for x in f_[:4])
        non = " & ".join(f"${fmt(x)}$" if x is not None else "--" for x in f_[4:7])
        lines.append(f"{name} & {left} & & {epi} & & {non} \\\\")
    lines.append("}")
    lines.append("")
    lines.append("% Table: field name contrast (high minus low)")
    lines.append("\\newcommand{\\TabField}{%")
    for name, bb, f_ in rows_field:
        cells = " & ".join(f"${fmt(x)}$" if x is not None else "--" for x in f_)
        lines.append(f"{name} & {cells} \\\\")
    lines.append("}")

    os.makedirs("paper", exist_ok=True)
    open(MACRO, "w").write("\n".join(lines) + "\n")
    print(f"{MACRO} 작성: {len(lines)}줄")
    print(f"  claim {rng(claim_vals)}  conf@high {rng(conf_hi)}")
    print(f"  conf/claim {rng(conf_share,0)}%   Priority/Confidence {rng(prio_share,0)}%")
    print("  field 열 순서: Confidence, Reliability, Certainty, Priority, Urgency, Metric-X")
