#!/usr/bin/env python3
"""Is the effect about epistemic wording, or about epistemic wording aimed at the claim?

Confidence, Reliability and Certainty all say how much to believe the claim in the block.
Priority, Urgency and Metric-X say nothing epistemic. That leaves one reading of the headline
gap open: perhaps the model responds to any field that carries meaning, and the non-epistemic
controls are simply meaningless. Metric-X blunts that -- it is opaque and still behaves like
Priority -- but opaque is itself a kind of meaningless.

`Prior: high` fills the missing cell: same block, same graded value, epistemic vocabulary, but
its referent is the class base rate rather than this clip's claim. If the effect is about
epistemic register, Prior should behave like Confidence. If it needs the epistemic content to
be *about the claim*, Prior should behave like the non-epistemic controls.

Same statistic as Table 1's field columns: order-averaged high-minus-low margin change on
unaided-correct items.
"""
from __future__ import annotations
import json, math, os, pathlib
import numpy as np

CELLS = [("Qwen2.5/sound", "s2", "sound"), ("Qwen2.5/colour", "s2", "colour"),
         ("Qwen2.5/noise-g4", "s2", "grad_noise_g4"), ("Qwen3/sound", "s2q3", "sound"),
         ("Qwen3/noise", "s2q3", "noise"), ("Qwen3/colour", "s2q3", "colour"),
         ("VideoLLaMA/colour", "s2vl", "colour"), ("Qwen2-Audio", "nm_qwen2audio", "sound"),
         ("Nemotron/sound", "nm_nemotron", "sound"), ("Nemotron/colour", "nm_nemotron", "colour")]

# Reuse the table's own contrast rather than reimplementing it. An earlier version of this
# script recomputed the margin here and produced numbers ten times smaller than Table 1's,
# because gen_macros' margin() corrects the swapped read-out and this one did not.
import sys
sys.path.insert(0, "scripts")
from gen_macros_v1 import avg


if __name__ == "__main__":
    print(f"{'cell':18} {'Confidence':>11} {'Prior':>8} {'Priority':>9}  {'|Prior|/|Conf|':>14}")
    print("-" * 66)
    rows = []
    for nm, pfx, attr in CELLS:
        c, pr, pi = (avg(pfx, attr, f"{p}_high", f"{p}_low")
                     for p in ("anon", "prior", "priority"))
        if None in (c, pr, pi):
            print(f"{nm:18} 데이터 부족")
            continue
        ratio = abs(pr) / abs(c) * 100
        rows.append((nm, c, pr, pi, ratio))
        print(f"{nm:18} {c:11.2f} {pr:8.2f} {pi:9.2f}  {ratio:13.0f}%")
    if rows:
        smaller = sum(1 for _, c, pr, _, _ in rows if abs(pr) < abs(c))
        like_non = sum(1 for _, c, pr, pi, _ in rows if abs(pr) - abs(pi) < abs(c) - abs(pr))
        rs = sorted(r[4] for r in rows)
        print(f"\n  |Prior| < |Confidence|: {smaller}/{len(rows)}")
        print(f"  Prior closer to the non-epistemic side: {like_non}/{len(rows)}")
        print(f"  |Prior|/|Confidence| median {rs[len(rs)//2]:.0f}% (range {rs[0]:.0f}--{rs[-1]:.0f}%)")
        pathlib.Path("paper/auto_prior.tex").write_text(
            "% Generated by scripts/analyse_prior_v1.py -- do not edit by hand.\n"
            f"\\newcommand{{\\PriorCells}}{{{len(rows)}}}\n"
            f"\\newcommand{{\\PriorSmallerN}}{{{smaller}}}\n"
            f"\\newcommand{{\\PriorLikeNonN}}{{{like_non}}}\n"
            f"\\newcommand{{\\PriorShareMed}}{{{rs[len(rs)//2]:.0f}}}\n"
            f"\\newcommand{{\\PriorShareMin}}{{{rs[0]:.0f}}}\n"
            f"\\newcommand{{\\PriorShareMax}}{{{rs[-1]:.0f}}}\n")
        print("paper/auto_prior.tex written")
