#!/usr/bin/env python3
"""E4 (preregistered 2026-09-07 10:25 KST): does a one-line caveat recover more than reformatting?

Per cascade cell, order-averaged accuracy against omitting the tag, with a source-video cluster
bootstrap (11-char YouTube ids):
    plain  = cascadex_plain  - none      the headline forwarding loss
    warn   = cascadex_warn   - none      plain + " This tag may be wrong; judge from the recording itself."
    block  = cascadex_bare   - none      the same claim inside a Source/Claim block
and the two paired contrasts the preregistration judges on: warn-minus-plain against
block-minus-plain. Reads outputs/ only.
"""
import json, os, re, sys
import numpy as np
OUT="outputs"; BOOTS=2000
CELLS=[("Qwen2.5-Omni","s2"),("Qwen3-Omni","s2q3"),("Qwen2-Audio","nm_qwen2audio"),("Nemotron/sound","nm_nemotron")]
def L(n):
    p=f"{OUT}/{n}_v1.jsonl"
    if not os.path.exists(p): return None
    d={json.loads(l)["clip"]:json.loads(l) for l in open(p) if l.strip()}
    return d if len(d)>=400 else None
def vid(c):
    b=os.path.basename(c); m=re.match(r"^(.{11})_\d{6}",b); return m.group(1) if m else b
def boot(pairs, keys):
    """pairs: list per order of (a_dict, b_dict); order-averaged mean of a-b with cluster CI."""
    vids=sorted({vid(k) for k in keys}); vi={v:i for i,v in enumerate(vids)}
    gi=np.array([vi[vid(k)] for k in keys]); buckets=[np.where(gi==i)[0] for i in range(len(vids))]
    ds=[np.array([a[k]["correct"]-b[k]["correct"] for k in keys],float) for a,b in pairs]
    pt=float(np.mean([d.mean()*100 for d in ds]))
    rng=np.random.default_rng(0); bs=[]
    for _ in range(BOOTS):
        sel=rng.integers(0,len(vids),len(vids)); idx=np.concatenate([buckets[i] for i in sel if buckets[i].size])
        bs.append(float(np.mean([d[idx].mean()*100 for d in ds])))
    return pt,float(np.percentile(bs,2.5)),float(np.percentile(bs,97.5))
def f(t): return "--" if t is None else f"{t[0]:+.1f} [{t[1]:+.1f},{t[2]:+.1f}]"
res={}
print(f"{'cell':16}{'plain-omit':>22}{'warn-omit':>22}{'block-omit':>22}{'warn-plain':>22}{'block-plain':>22}")
for name,pfx in CELLS:
    conds={}
    for c in ("none","cascadex_plain","cascadex_warn","cascadex_bare"):
        per=[(L(f"{pfx}_sound_{c}{t}")) for t in ("","_swap")]
        conds[c]=per if all(per) else None
    if conds["cascadex_warn"] is None:
        print(f"{name:16}{'warn not run':>22}"); continue
    keys=sorted(set.intersection(*(set(d) for c in conds if conds[c] for d in conds[c])))
    r={}
    for c,lab in (("cascadex_plain","plain"),("cascadex_warn","warn"),("cascadex_bare","block")):
        if conds[c]: r[lab]=boot(list(zip(conds[c],conds["none"])),keys)
    r["warn-plain"]=boot(list(zip(conds["cascadex_warn"],conds["cascadex_plain"])),keys)
    if conds["cascadex_bare"]: r["block-plain"]=boot(list(zip(conds["cascadex_bare"],conds["cascadex_plain"])),keys)
    res[name]=r
    print(f"{name:16}{f(r.get('plain')):>22}{f(r.get('warn')):>22}{f(r.get('block')):>22}{f(r['warn-plain']):>22}{f(r.get('block-plain')):>22}  n={len(keys)}")
if len(res)==len(CELLS):
    wp=[r["warn-plain"] for r in res.values()]; bp=[r["block-plain"] for r in res.values()]
    beats=sum(1 for w,b in zip(wp,bp) if w[1]>0 and w[0]>b[0])
    pos=sum(1 for w in wp if w[1]>0)
    full=sum(1 for n,r in res.items() if r["warn"][1]>0)   # warn recovers the loss entirely
    print(f"\nprereg: warn-plain CI>0 in {pos}/4; warn beats block in {beats}/4 -> "
          + ("(a) RETRACT 'serialisation is the lever'" if beats>=3 else "(b) keep conclusion, report the baseline" if pos<4 or beats<3 else "(b)"))
    print(f"warn fully recovers the omit-loss in {full}/4 cells")
    if "--macros" in sys.argv:
        M={"EFourWarnMin":f"{min(w[0] for w in wp):+.1f}","EFourWarnMax":f"{max(w[0] for w in wp):+.1f}",
           "EFourWarnPosN":str(pos),"EFourBeatsBlockN":str(beats),"EFourCells":"4",
           "EFourBlockMin":f"{min(b[0] for b in bp):+.1f}","EFourBlockMax":f"{max(b[0] for b in bp):+.1f}",
           "EFourStillLossN":str(sum(1 for r in res.values() if r["warn"][2]<0))}
        with open("paper/auto_e4.tex","w") as fh:
            fh.write("% Generated by research_reports/20260907_E4/analyse_e4_v1.py --macros -- do not edit by hand.\n")
            for k,v in M.items(): fh.write(f"\\newcommand{{\\{k}}}{{{v}}}\n")
        print("macros:",M)
